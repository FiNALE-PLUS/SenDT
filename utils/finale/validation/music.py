RESERVED_MUSIC_IDS = {997}

finale_safename_re = re.compile(r"^([a-z_0-9])+$")


def validate_music_id(song_id: int, additional_taken_music_ids: set[int] = None, patched_id_limit: bool = False) -> bool:
    disallowed_music_ids = VANILLA_MUSIC_IDS | RESERVED_MUSIC_IDS
    if additional_taken_music_ids is not None:
        disallowed_music_ids = disallowed_music_ids | additional_taken_music_ids

    if song_id in disallowed_music_ids:
        return False

    if not patched_id_limit and song_id >= 1000:
        return False

    return True


def validate_finale_music_safename(safename: str) -> bool:
    return finale_safename_re.search(safename) is not None
